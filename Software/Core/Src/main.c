static void DFPlayer_Send_Command(uint8_t cmd, uint16_t param){
	// On crée la trame de 10 octets selon le format fourni par la datasheet du DFPlayer

	uint8_t frame[10]={
			0x7E, // Octet de start
			0xFF, // Version
			0x06, // Longueur des données
			cmd,  // Commande
			0x00, // Acknowledge (0x00 = pas d'ACK)
			(uint8_t)(param>>8), // Octet de poids fort du paramètre 16 bits
			(uint8_t)(param & 0xFF), // Octet de poids faible du paramètre 16 bits
			0x00, // Octet de poids fort de la checksum 16 bits
			0x00, // Octet de poids faible de la checksum 16 bits
			0xEF  // Octet de fin
	};

	// Calcul de la checksum selon la formule : Checksum = 0 - (Version + Len + Cmd + Acknowledge + ParamM + ParamL)
	uint16_t sum = 0;
	for (uint8_t i = 1; i <= 6; i++) {
	    sum += frame[i];
	}
	uint16_t checksum = (uint16_t)(0xFFFF - sum + 1);

	frame[7] = (uint8_t)(checksum >> 8);
	frame[8] = (uint8_t)(checksum & 0xFF);

	HAL_UART_Transmit(&huart3, frame, 10, 50);
}
