void Task_Telemetry_Audio(void *pvParameters){
	TelemetryMsg_t rx_msg;

	vTaskDelay(pdMS_TO_TICKS(1500));
	DFPlayer_Send_Command(0x09, 0x0002);
	vTaskDelay(pdMS_TO_TICKS(200));
	DFPlayer_Send_Command(0x06, 20);
	vTaskDelay(pdMS_TO_TICKS(200));

	Robot_LogBLU("[BOOT] RTOS ready\r\n");

	for(;;){
		if (xQueueReceive(qTelemetry, &rx_msg, portMAX_DELAY) == pdTRUE){

			if (rx_msg.type == MSG_TYPE_LOG){
				TickType_t start = xTaskGetTickCount();
				while (blu_dma_busy == 1 && ((xTaskGetTickCount() - start) < pdMS_TO_TICKS(50))){
					vTaskDelay(pdMS_TO_TICKS(1));
				}

				uint16_t len = (uint16_t)strlen(rx_msg.text);

				if (len>0 && len<=sizeof(blu_dma_buf)){
					blu_dma_busy = 1;
					memcpy(blu_dma_buf, rx_msg.text, len);

					if (HAL_UART_Transmit_DMA(&huart2, blu_dma_buf, len)!= HAL_OK){
						blu_dma_busy = 0;
					}
				}
			}
			else if (rx_msg.type == MSG_TYPE_AUDIO_TRACK){
				DFPlayer_Send_Command(0x03, (uint16_t)rx_msg.audio_track);
			}
		}
	}
}

